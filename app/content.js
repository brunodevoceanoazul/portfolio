export const query = `SELECT month,
       SUM(requested) AS requested,
       SUM(completed) AS completed,
       ROUND(100.0 * SUM(completed)
         / NULLIF(SUM(requested), 0), 1) AS completion_pct
FROM request_metrics
GROUP BY month
ORDER BY month;`;

